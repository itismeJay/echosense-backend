def _term_params(terms) -> list[dict]:
    return [
        {"slur_text": text, "language": language, "severity_weight": weight}
        for text, language, weight in terms
    ]


def _stt_column(connection) -> str:
    columns = {column["name"] for column in sa.inspect(connection).get_columns("system_settings")}
    return "stt_model_version" if "stt_model_version" in columns else "vosk_version"


def seed(connection) -> None:
    connection.execute(sa.text(SYSTEM_SETTINGS_SEED.format(stt_column=_stt_column(connection))))
    connection.execute(sa.text(TERM_INSERT), _term_params(LEGACY_TERMS + EDGE_TERMS))


def unseed(connection) -> None:
    # The settings row is kept: the code before this revision also requires it.
    connection.execute(sa.text(TERM_DELETE), _term_params(EDGE_TERMS))


def upgrade() -> None:
    seed(op.get_bind())


def downgrade() -> None:
    unseed(op.get_bind())
